// Generates the extension's tutorial model from its typeDiagram source, so the
// TypeScript types and the model never drift. Implements [TUTORIAL-MODEL].
//
//   node tools/vsix/tutorial-model.mjs [--check]
//
// Requires the `typediagram` CLI on $PATH (.github/actions/typediagram).
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const source = path.join(root, "docs/models/vscode-tutorial.td");
const extensionDir = path.join(root, "src/editors/vscode");
const target = path.join(extensionDir, "src/tutorial/model.generated.ts");
const require = createRequire(path.join(extensionDir, "package.json"));
const prettier = require("prettier");
const { ESLint } = require("eslint");

const HEADER = `// @generated by tools/vsix/tutorial-model.mjs from docs/models/vscode-tutorial.td.
// DO NOT EDIT BY HAND: edit the model and run \`node tools/vsix/tutorial-model.mjs\`.
// Implements [TUTORIAL-MODEL].
`;

const emitted = execFileSync("typediagram", ["--to", "typescript", source], { encoding: "utf8" });
const options = (await prettier.resolveConfig(target)) ?? {};
// The extension's own lint fixes (e.g. `T[]` for `Array<T>`), then its formatting.
const [linted] = await new ESLint({ cwd: extensionDir, fix: true }).lintText(`${HEADER}\n${emitted}`, { filePath: target });
const generated = await prettier.format(linted.output ?? linted.source ?? "", { ...options, filepath: target });
const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";

if (process.argv.includes("--check")) {
  if (current !== generated) {
    process.stderr.write(`${path.relative(root, target)} is stale: run node tools/vsix/tutorial-model.mjs\n`);
    process.exit(1);
  }
} else if (current !== generated) {
  fs.writeFileSync(target, generated, "utf8");
  process.stdout.write(`tutorial-model: wrote ${path.relative(root, target)}\n`);
}
