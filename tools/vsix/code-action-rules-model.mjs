// Generates Rust, C#, and F# types and associated-rule tables from
// docs/models/code-action-rules.td and docs/models/code-action-rules.json.
// Implements [FIXALL-MODEL], [FIXALL-RULES], [FIXALL-RULES-TABLE].
//
//   node tools/vsix/code-action-rules-model.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitTypeDiagram, syncGeneratedFile } from "./typediagram-cli.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const modelPath = path.join(root, "docs/models/code-action-rules.td");
const rulesPath = path.join(root, "docs/models/code-action-rules.json");
const checkMode = process.argv.includes("--check");
const rules = JSON.parse(fs.readFileSync(rulesPath, "utf8"));

const HEADER = `// @generated by tools/vsix/code-action-rules-model.mjs from docs/models/code-action-rules.td and code-action-rules.json.
// DO NOT EDIT BY HAND: edit the model/table and run \`node tools/vsix/code-action-rules-model.mjs\`.
// Implements [FIXALL-MODEL], [FIXALL-RULES], [FIXALL-RULES-TABLE].`;

const q = (value) => JSON.stringify(value);

function buildRust() {
    const emitted = emitTypeDiagram("rust", modelPath)
        .replace(/^pub (enum|struct) /gm, "#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\npub $1 ")
        .trim();
    const entries = rules.map((assoc) => {
        const ruleExprs = assoc.rules.map((rule) => {
            const settingExprs = rule.settings.map((s) =>
                `RuleSetting { sink: RuleSink::${s.sink}, key: ${q(s.key)}.to_string(), value: ${q(s.value)}.to_string() }`
            ).join(", ");
            return `AssociatedRule { diagnosticId: ${q(rule.diagnosticId)}.to_string(), language: RuleLanguage::${rule.language}, title: ${q(rule.title)}.to_string(), settings: vec![${settingExprs}], severity: RuleSeverity::${rule.severity} }`;
        }).join(", ");
        return `        FixRuleAssociation { fixKey: ${q(assoc.fixKey)}.to_string(), language: RuleLanguage::${assoc.language}, rules: vec![${ruleExprs}] },`;
    }).join("\n");

    return `${HEADER}
#![cfg_attr(rustfmt, rustfmt::skip)]
#![allow(
    non_snake_case,
    dead_code,
    clippy::too_many_lines,
    clippy::missing_docs_in_private_items,
    reason = "generated from docs/models/code-action-rules.td by typediagram"
)]

${emitted}

/// All associated-rule entries from [FIXALL-RULES-TABLE].
pub fn associated_rules() -> Vec<FixRuleAssociation> {
    vec![
${entries}
    ]
}

/// Look up the rule association for a fix key (exact match, trailing suffix,
/// or Roslyn provider-qualified key).
pub fn find_association(fix_key: &str) -> Option<FixRuleAssociation> {
    let provider = fix_key.split('/').next().unwrap_or("");
    associated_rules().into_iter().find(|entry| {
        entry.fixKey == fix_key
            || fix_key.ends_with(&format!("/{}", entry.fixKey))
            || (!provider.is_empty() && provider.contains(&entry.fixKey))
    })
}
`;
}

function buildCSharp() {
    const emitted = emitTypeDiagram("csharp", modelPath)
        .replace(/^#nullable enable\s*/, "")
        .trim();
    const entries = rules.map((assoc) => {
        const ruleExprs = assoc.rules.map((rule) => {
            const settingExprs = rule.settings.map((s) =>
                `new RuleSetting(RuleSink.${s.sink}, ${q(s.key)}, ${q(s.value)})`
            ).join(", ");
            return `new AssociatedRule(${q(rule.diagnosticId)}, RuleLanguage.${rule.language}, ${q(rule.title)}, [${settingExprs}], RuleSeverity.${rule.severity})`;
        }).join(", ");
        return `        new FixRuleAssociation(${q(assoc.fixKey)}, RuleLanguage.${assoc.language}, [${ruleExprs}]),`;
    }).join("\n");

    return `// <auto-generated/>
${HEADER}
#nullable enable
#pragma warning disable CS1591 // Generated from docs/models/code-action-rules.td by typediagram

namespace SharpLsp.Sidecar.Common.FixAll;

${emitted}

public static class FixAllRuleTable
{
    public static IReadOnlyList<FixRuleAssociation> Associations { get; } =
    [
${entries}
    ];
}
`;
}

function buildFSharp() {
    const emitted = emitTypeDiagram("fsharp", modelPath)
        .replace(/^type (FixScope|RuleLanguage|RuleSink|RuleSeverity) =/gm, "[<RequireQualifiedAccess; NoComparison; NoEquality>]\ntype $1 =")
        .replace(/^type (RuleSetting|AssociatedRule|FixRuleAssociation|FixAllRequest) =/gm, "[<NoComparison; NoEquality>]\ntype $1 =")
        .trim();
    const entries = rules.map((assoc) => {
        const ruleExprs = assoc.rules.map((rule) => {
            const settingExprs = rule.settings.map((s) =>
                `{ sink = RuleSink.${s.sink}; key = ${q(s.key)}; value = ${q(s.value)} }`
            ).join("; ");
            return `{ diagnosticId = ${q(rule.diagnosticId)}; language = RuleLanguage.${rule.language}; title = ${q(rule.title)}; settings = [${settingExprs}]; severity = RuleSeverity.${rule.severity} }`;
        }).join("; ");
        return `        { fixKey = ${q(assoc.fixKey)}; language = RuleLanguage.${assoc.language}; rules = [${ruleExprs}] }`;
    }).join("\n");

    return `${HEADER}
// fsharplint:disable RecordFieldNames
module SharpLsp.Sidecar.FSharp.FixAllRules

${emitted}

let associations: FixRuleAssociation list =
    [
${entries}
    ]
`;
}

const outputs = [
    [path.join(root, "src/sharplsp/src/code_actions/rules_generated.rs"), buildRust()],
    [path.join(root, "src/sidecars/SharpLsp.Sidecar.Common/FixAllRules.g.cs"), buildCSharp()],
    [path.join(root, "src/sidecars/SharpLsp.Sidecar.FSharp/FixAllRules.g.fs"), buildFSharp()],
];

const ok = outputs.every(([target, content]) =>
    syncGeneratedFile(root, target, content, checkMode, "code-action-rules-model.mjs")
);
if (!ok) process.exit(1);
