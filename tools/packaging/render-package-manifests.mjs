#!/usr/bin/env node
// Render the Homebrew formula and the Scoop manifest for a release.
// [DIST-PATH-INSTALL] [DIST-ARCHIVE]
//
// Usage:
//   node tools/packaging/render-package-manifests.mjs \
//     --version 0.20.0 --repo Nimblesite/SharpLsp \
//     --archives artifacts --out dist/packaging
//
// Both files are generated whole from the release archives, never edited in
// place: the checksums must come from the bytes actually published, and a
// partial rewrite of an existing formula is how a stale sha256 survives a bump.
//
// The archive layout ([DIST-ARCHIVE-LAYOUT]) decides where each package manager
// must put the payload, because the host resolves its sidecars from its own
// location (`installed_sidecar_exe` in src/sharplsp/src/sidecar/manager.rs):
//
//   Homebrew  bin/sharplsp + lib/sharplsp/sidecar-*  -> resolution layout 2
//             (`<exe_dir>/../lib/sharplsp/<subdir>/<name>`)
//   Scoop     sharplsp.exe + sidecar-* beside it     -> resolution layout 1
//             (`<exe_dir>/<subdir>/<name>`)
//
// Getting either wrong yields an install that starts and then cannot reach
// Roslyn or FCS, so both are asserted by tools/packaging/verify-package-manifests.mjs.

import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

// `brew audit --strict` rejects a leading article and a desc over 80 characters.
const DESCRIPTION = "Open-source .NET language server with C# and F# intelligence";
const LICENSE = "MIT";

// darwin-x64 is absent on purpose: the macos-13 runner hangs building it, so the
// matrix entry in .github/workflows/release.yml is commented out. Adding it here
// without adding it there would publish a formula pointing at a missing asset.
const UNIX_PLATFORMS = ["darwin-arm64", "linux-x64", "linux-arm64"];
const WINDOWS_PLATFORMS = ["win32-x64", "win32-arm64"];

// Scoop's architecture keys, not ours.
const SCOOP_ARCH = { "win32-x64": "64bit", "win32-arm64": "arm64" };

// Kept as lines so the Homebrew caveats heredoc wraps instead of running off the
// terminal; Scoop's `notes` accepts the same array.
const DOTNET_NOTE = [
  "SharpLsp needs the .NET 10 SDK on PATH.",
  "The C# and F# sidecars are framework-dependent, and only the VS Code",
  "extension acquires the SDK for you.",
];

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 2) {
    const key = argv[i];
    if (!key.startsWith("--")) throw new Error(`unexpected argument: ${key}`);
    const value = argv[i + 1];
    if (value === undefined) throw new Error(`missing value for ${key}`);
    args[key.slice(2)] = value;
  }
  for (const required of ["version", "repo", "archives", "out"]) {
    if (!args[required]) throw new Error(`--${required} is required`);
  }
  return args;
}

/** Every file under `dir`, recursively — download-artifact nests by artifact name. */
function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(path));
    else out.push(path);
  }
  return out;
}

/** sha256 of the published bytes, keyed by archive filename. */
function hashArchives(archivesDir, names) {
  const files = walk(resolve(archivesDir));
  const hashes = {};
  for (const name of names) {
    const matches = files.filter((f) => f.endsWith(`/${name}`) || f.endsWith(`\\${name}`));
    if (matches.length === 0) {
      throw new Error(`missing release archive ${name} under ${archivesDir}`);
    }
    // Read ONCE and judge the bytes in hand. Sizing the path with `statSync`
    // and then reading it again is a check the read cannot rely on — the file
    // may change in between (CodeQL js/file-system-race) — and it walks a
    // release archive twice for no gain.
    const bytes = readFileSync(matches[0]);
    if (bytes.length === 0) {
      throw new Error(`release archive ${name} is empty`);
    }
    hashes[name] = createHash("sha256").update(bytes).digest("hex");
  }
  return hashes;
}

function renderFormula({ version, repo, hashes }) {
  const base = `https://github.com/${repo}/releases/download/v${version}`;
  const block = (platform, indent) => {
    const name = `sharplsp-${platform}.tar.gz`;
    return [
      `${indent}url "${base}/${name}"`,
      `${indent}sha256 "${hashes[name]}"`,
    ].join("\n");
  };

  return `# Generated by tools/packaging/render-package-manifests.mjs. Do not edit by hand.
class Sharplsp < Formula
  desc "${DESCRIPTION}"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "${LICENSE}"

  on_macos do
    # No darwin-x64 archive is published — that build hangs on GitHub's hosted
    # macos-13 runners, so its matrix entry is commented out in release.yml.
    # Declaring the requirement gives Intel Macs a clear architecture error
    # instead of a 404 mid-download.
    depends_on arch: :arm64
${block("darwin-arm64", "    ")}
  end

  on_linux do
    on_arm do
${block("linux-arm64", "      ")}
    end
    on_intel do
${block("linux-x64", "      ")}
    end
  end

  # The archive is not a bare binary: \`sharplsp\` spawns a Roslyn sidecar and an
  # FCS sidecar, and finds them RELATIVE TO ITSELF. \`lib/sharplsp/\` is the
  # \`<exe_dir>/../lib/sharplsp/<subdir>/\` layout the host already looks in, so
  # installing them here needs no wrapper script and no environment variable.
  # Installing only the binary would produce a language server that starts and
  # then answers nothing.
  def install
    bin.install "sharplsp"
    (lib/"sharplsp").install "sidecar-csharp", "sidecar-fsharp"
  end

  # Deliberately no \`depends_on "dotnet"\`: the sidecars target net10.0 and the
  # Homebrew dotnet formula is not pinned to that. Say so instead of installing
  # a runtime that cannot load them.
  def caveats
    <<~EOS
${DOTNET_NOTE.map((line) => `      ${line}`).join("\n")}
    EOS
  end

  test do
    assert_match "sharplsp #{version}", shell_output("#{bin}/sharplsp --version")
  end
end
`;
}

function buildScoopManifest({ version, repo, hashes }) {
  const base = `https://github.com/${repo}/releases/download/v${version}`;
  const architecture = {};
  const autoupdateArchitecture = {};
  for (const platform of WINDOWS_PLATFORMS) {
    const name = `sharplsp-${platform}.zip`;
    architecture[SCOOP_ARCH[platform]] = {
      url: `${base}/${name}`,
      hash: hashes[name],
      // Strips the archive's top-level directory, leaving sharplsp.exe with
      // sidecar-csharp/ and sidecar-fsharp/ beside it — resolution layout 1.
      extract_dir: `sharplsp-${platform}`,
    };
    autoupdateArchitecture[SCOOP_ARCH[platform]] = {
      url: `https://github.com/${repo}/releases/download/v$version/sharplsp-${platform}.zip`,
      extract_dir: `sharplsp-${platform}`,
    };
  }

  return {
    version,
    description: DESCRIPTION,
    homepage: `https://github.com/${repo}`,
    license: LICENSE,
    notes: DOTNET_NOTE.join(" "),
    architecture,
    // Only the host is shimmed onto PATH. The sidecars are spawned by it from
    // the app directory and must NOT get their own shims.
    bin: ["sharplsp.exe"],
    checkver: { github: `https://github.com/${repo}` },
    autoupdate: { architecture: autoupdateArchitecture },
  };
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const names = [
    ...UNIX_PLATFORMS.map((p) => `sharplsp-${p}.tar.gz`),
    ...WINDOWS_PLATFORMS.map((p) => `sharplsp-${p}.zip`),
  ];
  const hashes = hashArchives(args.archives, names);

  const outDir = resolve(args.out);
  mkdirSync(outDir, { recursive: true });

  const formulaPath = join(outDir, "sharplsp.rb");
  const manifestPath = join(outDir, "sharplsp.json");
  writeFileSync(formulaPath, renderFormula({ ...args, hashes }));
  writeFileSync(
    manifestPath,
    `${JSON.stringify(buildScoopManifest({ ...args, hashes }), null, 2)}\n`,
  );

  process.stdout.write(`wrote ${formulaPath}\nwrote ${manifestPath}\n`);
}

main();
